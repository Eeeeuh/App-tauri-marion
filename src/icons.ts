/** Replaces every `<span data-icon="name">` placeholder in a subtree. */
export function hydrateIcons(root: ParentNode): void {
  root.querySelectorAll<HTMLElement>("[data-icon]").forEach((el) => {
    el.outerHTML = icon(el.dataset.icon!);
  });
}
